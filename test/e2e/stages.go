// stageGenerate runs the scaffold's own generate, with reviewable on top for
// head. A release's reviewable lints and tests an old scaffold, which says
// nothing about this build. The stages after it need only the generated files.
func stageGenerate(e *Env) error {
	targets := []string{"submodules", targetGenerate}
	if !e.Case.Release() {
		targets = append(targets, "reviewable")
	}
	if err := e.make(targets...); err != nil {
		return err
	}
	for _, kind := range []string{"widget", "gadget"} {
		for _, rel := range []string{
			fmt.Sprintf("package/crds/%s.%s_%ss.yaml", group, domain, kind),
			fmt.Sprintf("examples/%s/%s.yaml", group, kind),
		} {
			if _, err := os.Stat(e.path(rel)); err != nil {
				return fmt.Errorf("generate left no %s: %w", rel, err)
			}
		}
	}
	if err := e.assertOwnership(); err != nil {
		return err
	}
	if err := e.assertCleanTree("generate"); err != nil {
		return err
	}
	subjects, err := e.git("log", "--format=%s")
	if err != nil {
		return err
	}
	if subjects != initialCommitMsg {
		return fmt.Errorf("want one Initial commit, git log has:\n%s", subjects)
	}
	return nil
}

// stageUserLogic lints the overlay for head only; on a release, update's own
// make reviewable lints the same overlay.
func stageUserLogic(e *Env) error {
	if err := e.copyOverlay(); err != nil {
		return err
	}
	if err := e.addProviderConfigField(); err != nil {
		return err
	}
	if _, err := e.exec(e.Dir, "", "go", "mod", "tidy"); err != nil {
		return err
	}
	targets := []string{targetGenerate}
	if !e.Case.Release() {
		targets = append(targets, "lint")
	}
	if err := e.make(targets...); err != nil {
		return err
	}
	if err := e.F.AssertUserLogic(e); err != nil {
		return err
	}
	return e.commit(userLogicMsg)
}

// stageUpdateToHead plants a stale go directive, because a release and head
// can share one and the directive check would then pass on a file update never
// touched. Head's update must then leave every user-owned file alone, move the
// go directive to the one head pins, stamp PROJECT with head's version, and
// keep the ownership contract. The stages that deploy and reconcile run on the
// updated tree, so a provider that does not come up Ready fails there.
func stageUpdateToHead(e *Env) error {
	userOwned, err := e.userOwned()
	if err != nil {
		return err
	}
	wantGo, err := e.headGoVersion()
	if err != nil {
		return err
	}
	if err := e.setGoDirective(staleGoDir); err != nil {
		return err
	}
	if err := e.commit("simulate a go directive older than head's"); err != nil {
		return err
	}
	if _, err := e.head("update"); err != nil {
		return err
	}
	if err := e.measureUpgrade(userOwned, wantGo); err != nil {
		return err
	}
	if err := e.F.AssertUserLogic(e); err != nil {
		return err
	}
	return e.commit("update to head")
}

// measureUpgrade takes every upgrade count before it fails on any, so a report
// of a failed run still says how far off the update was. The checks of what
// update itself wrote come before generate, which could otherwise rewrite
// go.mod and hide a directive update left behind.
func (e *Env) measureUpgrade(userOwned map[string][]byte, wantGo string) error {
	var up Upgrade
	var userErr, toolErr, genErr error
	up.UserOwnedChanged, userErr = e.assertUserOwnedUnchanged(userOwned)
	up.ToolOwnedCompared, up.ToolOwnedDiffering, toolErr = e.assertToolOwnedMatchesFreshScaffold()
	updatedErr := e.assertUpdated(wantGo)
	up.GeneratedChanged, genErr = e.assertGenerateChangesNothing()
	e.Upgrade = &up
	return errors.Join(userErr, toolErr, updatedErr, genErr)
}

// assertUpdated checks what head's update stamps and moves: the stamp, the go
// directive, and the ownership contract.
func (e *Env) assertUpdated(wantGo string) error {
	if err := e.assertStampIsHeadVersion(); err != nil {
		return err
	}
	got, err := e.goDirective()
	if err != nil {
		return err
	}
	if got != wantGo {
		return fmt.Errorf("go directive is %q after update, want head's %q", got, wantGo)
	}
	return e.assertOwnership()
}

// assertStampIsHeadVersion compares without the leading v and without quotes:
// the version command adds a v to a bare commit hash, which a checkout without
// tags reports, and the stamp does not; PROJECT quotes a hash of only digits.
func (e *Env) assertStampIsHeadVersion() error {
	want, err := e.head("version")
	if err != nil {
		return err
	}
	got, err := e.stamp()
	if err != nil {
		return err
	}
	if strings.TrimPrefix(strings.Trim(got, `"`), "v") != strings.TrimPrefix(want, "v") {
		return fmt.Errorf("PROJECT stamp is %q, want head's version %q", got, want)
	}
	return nil
}

func (e *Env) headGoVersion() (string, error) {
	b, err := os.ReadFile(filepath.Join(e.Repo, "pkg/versions/dependencies.yaml"))
	if err != nil {
		return "", err
	}
	m := headGoVersion.FindSubmatch(b)
	if m == nil {
		return "", fmt.Errorf("pkg/versions/dependencies.yaml has no go_version")
	}
	return string(m[1]), nil
}

func (e *Env) goDirective() (string, error) {
	mod, err := e.read("go.mod")
	if err != nil {
		return "", err
	}
	m := goDirective.FindStringSubmatch(mod)
	if m == nil {
		return "", fmt.Errorf("go.mod has no go directive")
	}
	return m[1], nil
}

func (e *Env) setGoDirective(version string) error {
	mod, err := e.read("go.mod")
	if err != nil {
		return err
	}
	if !goDirective.MatchString(mod) {
		return fmt.Errorf("go.mod has no go directive")
	}
	return e.write("go.mod", []byte(goDirective.ReplaceAllString(mod, "go "+version)))
}

// stageOrphanRemoval tracks a file that carries the generated header but that
// no template renders. update must remove it, name it and touch nothing else,
// and must leave a gitignored file with the same header alone.
func stageOrphanRemoval(e *Env) error {
	planted := map[string]string{orphanPath: generatedHead + "\n", ignoredPath: generatedHead + "\n\npackage x\n"}
	for rel, body := range planted {
		if err := os.MkdirAll(filepath.Dir(e.path(rel)), 0o750); err != nil {
			return err
		}
		if err := e.write(rel, []byte(body)); err != nil {
			return err
		}
	}
	if err := e.commit("track a file no template renders"); err != nil {
		return err
	}
	out, err := e.head("update")
	if err != nil {
		return err
	}
	for _, want := range []string{"removed 1", "removed " + orphanPath} {
		if err := contains(out, want, "update with an orphan"); err != nil {
			return err
		}
	}
	if _, err := os.Stat(e.path(orphanPath)); err == nil {
		return fmt.Errorf("update left the orphan %s", orphanPath)
	}
	if _, err := os.Stat(e.path(ignoredPath)); err != nil {
		return fmt.Errorf("update deleted the gitignored %s: %w", ignoredPath, err)
	}
	if err := e.assertOnlyOrphanChanged(); err != nil {
		return err
	}
	return e.commit("orphan removed")
}

func (e *Env) assertOnlyOrphanChanged() error {
	status, err := e.git("status", "--porcelain")
	if err != nil {
		return err
	}
	for _, line := range strings.Split(status, "\n") {
		if line = strings.TrimSpace(line); line != "D "+orphanPath && !strings.HasSuffix(line, " docs/ownership.md") {
			return fmt.Errorf("update touched more than the orphan and docs/ownership.md:\n%s", status)
		}
	}
	return nil
}

func stageUpdateNoop(e *Env) error {
	seams, err := e.readSeams()
	if err != nil {
		return err
	}
	out, err := e.head("update")
	if err != nil {
		return err
	}
	for _, want := range []string{"removed 0", "Refreshed 0 tool-owned file(s)"} {
		if err := contains(out, want, "same-generator update"); err != nil {
			return err
		}
	}
	if !unchanged.MatchString(out) {
		return fmt.Errorf("same-generator update reported no unchanged files:\n%s", out)
	}
	if err := e.assertSeamsUnchanged(seams, "update"); err != nil {
		return err
	}
	if err := e.assertOwnership(); err != nil {
		return err
	}
	if err := e.assertCleanTree("a same-generator update"); err != nil {
		return err
	}

	if err := e.appendLine(e.F.UserProbe, "// dirty"); err != nil {
		return err
	}
	out, err = e.head("update")
	if err := refused(out, err, "working tree", "update on a dirty tree"); err != nil {
		return err
	}
	if _, err := e.git("checkout", "--", e.F.UserProbe); err != nil {
		return err
	}
	if e.F.RefusesTerraformVersion {
		out, err = e.head("update", "--terraform-provider-version=1.0.0")
		if err := refused(out, err, `flavor is "native"`, "update --terraform-provider-version"); err != nil {
			return err
		}
	}
	return e.assertCleanTree("the refused attempts")
}

func stageCreateAPIRefresh(e *Env) error {
	createProbe := e.F.CreateAPI(e.F.ProbeKind)
	if err := e.refreshKeepsUserEdits(createProbe); err != nil {
		return err
	}
	before, err := e.git("rev-parse", "HEAD")
	if err != nil {
		return err
	}
	out, err := e.head(createProbe...)
	if err != nil {
		return err
	}
	if err := contains(out, "No changes to commit", "second create api"); err != nil {
		return err
	}
	if after, err := e.git("rev-parse", "HEAD"); err != nil || after != before {
		return fmt.Errorf("second create api moved HEAD from %s to %s", before, after)
	}
	out, err = e.head(append(createProbe, "--force")...)
	if err := refused(out, err, "unknown flag: --force", "create api --force"); err != nil {
		return err
	}
	return e.assertCleanTree("the refused --force attempt")
}

// refreshKeepsUserEdits marks a tool-owned and a user-owned file, re-runs
// create api, and asserts only the tool-owned mark is gone.
func (e *Env) refreshKeepsUserEdits(create []string) error {
	const toolMark, userMark = "// REFRESH-MARKER: stale tool-owned content", "// REFRESH-MARKER: user customization"
	if err := e.appendLine(e.F.ToolProbe, toolMark); err != nil {
		return err
	}
	if err := e.appendLine(e.F.UserProbe, userMark); err != nil {
		return err
	}
	if err := e.commit("simulate drift"); err != nil {
		return err
	}
	if _, err := e.head(create...); err != nil {
		return err
	}
	tool, err := e.read(e.F.ToolProbe)
	if err != nil {
		return err
	}
	user, err := e.read(e.F.UserProbe)
	if err != nil {
		return err
	}
	if strings.Contains(tool, toolMark) {
		return fmt.Errorf("stale tool-owned %s survived create api", e.F.ToolProbe)
	}
	if !strings.Contains(user, userMark) {
		return fmt.Errorf("user-owned %s was overwritten by create api", e.F.UserProbe)
	}
	return nil
}

// stock returns the clone stageStockClone makes and stageStockE2E runs in.
func (e *Env) stock() string { return filepath.Join(e.Work, "stock") }

// stageStockClone checks out the flavor's stock commit into a clone of its own
// before stock-e2e starts, because stock-e2e runs beside stages that change
// the provider directory.
func stageStockClone(e *Env) error {
	rev, err := e.git("log", "--format=%H", "--fixed-strings", "--grep="+e.F.StockMsg, "-n1")
	if err == nil && rev == "" {
		err = fmt.Errorf("no commit is named %q", e.F.StockMsg)
	}
	if err != nil {
		return err
	}
	if _, err := e.exec(e.Work, "", "git", "clone", "-q", e.Dir, e.stock()); err != nil {
		return err
	}
	_, err = e.exec(e.stock(), "", "git", "checkout", "-q", rev)
	return err
}

// stageStockE2E runs the author's entry point, make e2e, on the clone of the
// scaffold as the generator wrote it: the flavor's stock commit, before the
// update. The head's create-test adds a lifecycle test first, so the one run
// covers uptest, the tests the scaffold ships and the test create-test wrote.
// Native runs the unmodified stub from its first commit. Upjet has no stub to
// run: its stock commit holds the generated provider and the author's example.
//
// Uptest's update step does not run here, and that is expected. Uptest v2.2.0
// (internal/tester.go) makes a root of an example with meta.upbound.io/example-id
// and renders an update step only for a root with uptest.upbound.io/update-parameter.
// The scaffold ships neither: 01-update.yaml.tmpl emits `try:` inside `if .Root`,
// so two annotated roots in one run render a duplicate key. mr-update covers updates.
//
// It brings up the run's one kind cluster, KIND_CLUSTER_NAME, which install-in-kind
// brings up again: the stage that joins it, install-in-kind, starts on none
// because e2e-clean below deletes it.
func stageStockE2E(e *Env) error {
	stock := e.stock()
	defer func() { _, _ = e.makeIn(stock, "e2e-clean") }()
	if _, err := e.makeIn(stock, "submodules"); err != nil {
		return err
	}
	if _, err := e.exec(stock, "", e.Head, cmdCreateTest, "--kind="+e.F.TestKind, "--name="+lifecycleTest); err != nil {
		return err
	}
	if _, err := e.makeIn(stock, "e2e"); err != nil {
		return err
	}
	return assertChainsawRan(filepath.Join(stock, "junit.xml"))
}

// junitReport is the part of chainsaw's JUnit report assertChainsawRan reads:
// testsuites > testsuite > testcase, with a skipped, failure or error child on
// a test that did not pass.
type junitReport struct {
	Cases []struct {
		Name    string    `xml:"name,attr"`
		Skipped *struct{} `xml:"skipped"`
		Failure *struct{} `xml:"failure"`
		Error   *struct{} `xml:"error"`
	} `xml:"testsuite>testcase"`
}

// assertChainsawRan fails unless the chainsaw report holds a passed lifecycle
// testcase: make e2e's exit alone is the same whether or not chainsaw ran, and
// a skipped test still names itself in the report.
func assertChainsawRan(report string) error {
	b, err := os.ReadFile(report) // #nosec G304 -- a fixed path inside the private work directory
	if err != nil {
		return fmt.Errorf("reading the chainsaw report: %w", err)
	}
	var r junitReport
	if err := xml.Unmarshal(b, &r); err != nil {
		return fmt.Errorf("parsing %s: %w", report, err)
	}
	for _, c := range r.Cases {
		if c.Name != lifecycleTest {
			continue
		}
		if c.Skipped != nil || c.Failure != nil || c.Error != nil {
			return fmt.Errorf("%s shows the %s test skipped or failed", report, lifecycleTest)
		}
		return nil
	}
	return fmt.Errorf("%s does not show the %s test having run", report, lifecycleTest)
}

// pollRuntimeConfig is the DeploymentRuntimeConfig the harness deploys the
// provider with: the build's default plus a short --poll, so drift-corrected
// waits seconds instead of the shipped one-minute poll interval. The build
// swaps in the image, so none is set here.
const pollRuntimeConfig = `apiVersion: pkg.crossplane.io/v1beta1
kind: DeploymentRuntimeConfig
metadata:
  name: runtimeconfig-` + provider + `
spec:
  deploymentTemplate:
    spec:
      selector: {}
      template:
        spec:
          containers:
            - name: package-runtime
              args: ["--debug", "` + pollArg + `"]
`

func stageInstallInKind(e *Env) error {
	drc := filepath.Join(e.Work, "runtimeconfig.yaml")
	if err := os.WriteFile(drc, []byte(pollRuntimeConfig), 0o600); err != nil {
		return err
	}
	deploy := "local.xpkg.deploy.provider." + provider
	if err := e.make("DRC_FILE="+drc, "controlplane.down", "controlplane.up", deploy); err != nil {
		return err
	}
	if _, err := e.kubectl("", "wait", "provider.pkg", provider, "--for=condition=Healthy", "--timeout=300s"); err != nil {
		return err
	}
	// The build falls back to its own runtime config when DRC_FILE is missing,
	// so a pass above does not show the short poll was applied.
	out, err := e.kubectl("", "get", "deployment", "-A", "-o", "json")
	if err != nil {
		return err
	}
	if err := assertProviderPolls(out); err != nil {
		return err
	}
	if e.F.Live.Installed == nil {
		return nil
	}
	return e.F.Live.Installed(e)
}

// assertProviderPolls fails unless the provider's deployment, found by its
// selector, runs a container with pollArg.
func assertProviderPolls(deployments string) error {
	var list struct {
		Items []struct {
			Spec struct {
				Selector struct {
					MatchLabels map[string]string `json:"matchLabels"` //nolint:tagliatelle // Kubernetes API field name
				} `json:"selector"`
				Template struct {
					Spec struct {
						Containers []struct {
							Args []string `json:"args"`
						} `json:"containers"`
					} `json:"spec"`
				} `json:"template"`
			} `json:"spec"`
		} `json:"items"`
	}
	if err := json.Unmarshal([]byte(deployments), &list); err != nil {
		return fmt.Errorf("reading the deployments: %w", err)
	}
	for _, d := range list.Items {
		if d.Spec.Selector.MatchLabels[providerLabel] != provider {
			continue
		}
		for _, c := range d.Spec.Template.Spec.Containers {
			if slices.Contains(c.Args, pollArg) {
				return nil
			}
		}
		return fmt.Errorf("provider deployment args lack %s", pollArg)
	}
	return fmt.Errorf("no deployment carries %s=%s", providerLabel, provider)
}

func nativeProviderConfig(e *Env) error {
	creds, err := e.exec(e.Dir, "", e.tool("kind"), "get", "kubeconfig", "--internal", "--name", e.Cluster)
	if err != nil {
		return err
	}
	if _, err := e.kubectl("", "apply", "-f", "examples/provider/config.yaml"); err != nil {
		return err
	}
	// The example's Secret holds placeholder credentials; replace them with
	// the kubeconfig the overlay client dials the external system with.
	f := filepath.Join(e.Work, "internal.kubeconfig")
	if err := os.WriteFile(f, []byte(creds), 0o600); err != nil {
		return err
	}
	secret, err := e.kubectl("", "-n", externalNS, "create", "secret", "generic", "example-provider-secret",
		"--from-file=credentials="+f, "--dry-run=client", "-o", "yaml")
	if err != nil {
		return err
	}
	if _, err = e.kubectl(secret, "apply", "-f", "-"); err != nil {
		return err
	}
	return e.assertEndpointSurvivesInCluster()
}

